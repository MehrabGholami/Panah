    def h1(self, text):
        self.index += 1
        p = self.doc.add_heading(f"{self.index}. {text}", level=1)
        set_paragraph_rtl(p)

    def h2(self, text, num=None):
        p = self.doc.add_heading(text if num is None else f"{self.index}.{num} {text}", level=2)
        set_paragraph_rtl(p)

    def h3(self, text):
        p = self.doc.add_heading(text, level=3)
        set_paragraph_rtl(p)

    def p(self, text, bold_prefix=None):
        p = self.doc.add_paragraph()
        set_paragraph_rtl(p)
        if bold_prefix and text.startswith(bold_prefix):
            r = p.add_run(bold_prefix)
            r.bold = True
            r.font.name = "B Nazanin"
            r.font.size = Pt(13)
            r2 = p.add_run(text[len(bold_prefix):])
            r2.font.name = "B Nazanin"
            r2.font.size = Pt(13)
        else:
            r = p.add_run(text)
            r.font.name = "B Nazanin"
            r.font.size = Pt(13)
        return p

    def bullets(self, items):
        for text in items:
            p = self.doc.add_paragraph(style="List Bullet")
            set_paragraph_rtl(p)
            r = p.add_run(text)
            r.font.name = "B Nazanin"
            r.font.size = Pt(13)

    def numbered(self, items):
        for text in items:
            p = self.doc.add_paragraph(style="List Number")
            set_paragraph_rtl(p)
            r = p.add_run(text)
            r.font.name = "B Nazanin"
            r.font.size = Pt(13)

    def table(self, headers, rows, caption=None):
        if caption:
            p = self.doc.add_paragraph()
            set_paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
            r = p.add_run(caption)
            r.bold = True
            r.font.name = "B Nazanin"
            r.font.size = Pt(12)
            r.font.color.rgb = RGBColor(0x0F, 0x3A, 0x5F)
        table = self.doc.add_table(rows=1 + len(rows), cols=len(headers))
        table.style = "Table Grid"
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        for j, text in enumerate(headers):
            cell = table.cell(0, j)
            cell.text = str(text)
            set_cell_shading(cell, "0F3A5F")
            set_cell_rtl(cell)
            for run in cell.paragraphs[0].runs:
                run.font.color.rgb = RGBColor(255, 255, 255)
                run.bold = True
                run.font.name = "B Nazanin"
                run.font.size = Pt(11)
        for i, row in enumerate(rows):
            for j, value in enumerate(row):
                cell = table.cell(i + 1, j)
                cell.text = str(value)
                set_cell_rtl(cell)
                cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
                if i % 2 == 0:
                    set_cell_shading(cell, "F1F5F9")
                for run in cell.paragraphs[0].runs:
                    run.font.name = "B Nazanin"
                    run.font.size = Pt(11)
        self.doc.add_paragraph()

    def figure(self, path, caption, width=6.4):
        self.doc.add_picture(str(path), width=Inches(width))
        p = self.doc.paragraphs[-1]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c = self.doc.add_paragraph()
        set_paragraph_rtl(c, WD_ALIGN_PARAGRAPH.CENTER)
        r = c.add_run(caption)
        r.font.name = "B Nazanin"
        r.font.size = Pt(11)
        r.bold = True
        r.font.color.rgb = RGBColor(0x33, 0x41, 0x55)

    def page_break(self):
        self.doc.add_page_break()

    def save(self):
        self.doc.save(str(OUT))


