def pil_font(size, bold=False):
    if FONT:
        return ImageFont.truetype(FONT, size)
    return ImageFont.load_default()


def add_shape(draw, box, text, fill, outline="#0f172a", text_fill="#0f172a", size=15):
    draw.rounded_rectangle(box, radius=16, fill=fill, outline=outline, width=2)
    font = pil_font(size)
    lines = text.split("\n")
    total = sum(draw.textbbox((0, 0), line, font=font)[3] for line in lines)
    y = box[1] + (box[3] - box[1] - total) / 2
    for line in lines:
        bb = draw.textbbox((0, 0), line, font=font)
        x = box[0] + (box[2] - box[0] - (bb[2] - bb[0])) / 2
        draw.text((x, y), line, font=font, fill=text_fill)
        y += bb[3] - bb[1] + 3


def arrow(draw, a, b, fill="#475569"):
    draw.line([a, b], fill=fill, width=4)
    x, y = b
    draw.polygon([(x, y), (x - 12, y - 7), (x - 12, y + 7)], fill=fill)


